MULTI_SPLIT = re.compile(r"[·ㆍ,]")
PT_ITEM = re.compile(r"\[\d+\]")
LAW_SPLIT = re.compile(r"[,，]\s*")

def score_one(path):
    try:
        d = json.load(open(path, encoding="utf-8"))["PrecService"]
    except Exception:
        return None
    body = d.get("판례내용") or ""
    pts = d.get("판시사항") or ""
    summ = d.get("판결요지") or ""
    laws = d.get("참조조문") or ""
    precs = d.get("참조판례") or ""
    name = d.get("사건명") or ""
    text = pts + "\n" + summ + "\n" + body
    L = len(body)
    s = 0.0
    detail = Counter()
    for t, w in HARD_TERMS.items():
        c = text.count(t)
        if c:
            k = w * min(c, 3) ** 0.5
            s += k
            detail[t] = c
    n_pts = len(PT_ITEM.findall(pts))
    n_laws = len(re.findall(r"제\d+조", laws))
    n_lawnames = len(set(re.findall(r"([가-힣A-Za-z0-9·]+법(?:률)?(?:\s?시행령|\s?시행규칙)?)\s?제", laws)))
    n_precs = len(re.findall(r"\d{2,4}[가-힣]{1,3}\d+", precs))
    n_claims = len(MULTI_SPLIT.split(name)) if name else 0
    n_parties = len(re.findall(r"【(?:원고|피고|피고인|신청인|피신청인|참가인|피상고인|상고인|항소인|피항소인)[^】]*】", body))
    s += 3 * n_pts + 0.8 * n_laws + 2.5 * n_lawnames + 1.2 * n_precs + 2 * max(0, n_claims - 1) + 1.0 * n_parties
    s += min(L, 200000) / 4000.0
    top = ",".join(f"{t}:{c}" for t, c in detail.most_common(12))
    return {
        "file": os.path.basename(path),
        "사건번호": d.get("사건번호", ""),
        "법원명": d.get("법원명", ""),
        "선고일자": d.get("선고일자", ""),
        "사건종류명": d.get("사건종류명", ""),
        "사건명": name[:120],
        "score": round(s, 1),
        "본문길이": L,
        "판시항목": n_pts,
        "참조조문수": n_laws,
        "참조법률수": n_lawnames,
        "참조판례수": n_precs,
        "청구수": n_claims,
        "당사자표기": n_parties,
        "신호": top,
    }

def main():
    files = sorted(os.listdir(ROOT))
    rows = []
    for i, f in enumerate(files):
        if not f.endswith(".json"):
            continue
        r = score_one(os.path.join(ROOT, f))
        if r:
            rows.append(r)
        if i % 10000 == 0:
            print(i, file=sys.stderr, flush=True)
    rows.sort(key=lambda r: -r["score"])
    with open(OUT, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows[:3000])
    print("done", len(rows), file=sys.stderr)

if __name__ == "__main__":
    main()
